# ======================================================
# PDF REPORT GENERATOR
# ======================================================
def create_career_report(
    target_role,
    branch,
    readiness,
    skill_score,
    ats_score,
    placement_prob,
    confidence_level,
    projects,
    internships,
    skills,
    gap_items,
    actions
):
    buffer = BytesIO()

    pdf = canvas.Canvas(
        buffer,
        pagesize=A4
    )

    width, height = A4

    # Title
    pdf.setFont("Helvetica-Bold", 20)
    pdf.drawString(
        50,
        height - 60,
        "Adaptive Placement Coach"
    )

    pdf.setFont("Helvetica", 11)
    pdf.drawString(
        50,
        height - 82,
        "Personal Career Readiness Report"
    )

    y = height - 120

    # Candidate Overview
    pdf.setFont("Helvetica-Bold", 14)
    pdf.drawString(
        50,
        y,
        "Candidate Overview"
    )

    y -= 25

    pdf.setFont("Helvetica", 11)

    overview = [
        f"Target Role: {target_role}",
        f"Branch / Domain: {branch}",
        f"Confidence Level: {confidence_level}/5",
        f"Projects: {projects}",
        f"Internships: {internships}",
        f"Technical Skills: {', '.join(skills) if skills else 'None selected'}"
    ]

    for item in overview:
        pdf.drawString(60, y, item)
        y -= 18

    # Scores
    y -= 15

    pdf.setFont("Helvetica-Bold", 14)
    pdf.drawString(
        50,
        y,
        "Assessment Summary"
    )

    y -= 25

    pdf.setFont("Helvetica", 11)

    scores = [
        f"Model-Estimated Placed Class: {placement_prob:.1f}%",
        f"Readiness Index: {readiness:.1f}/100",
        f"Skill Coverage: {skill_score}/100",
        f"ATS Readiness (Simulated): {ats_score:.1f}%"
    ]

    for score in scores:
        pdf.drawString(60, y, score)
        y -= 18

    # Skill Gaps
    y -= 15

    pdf.setFont("Helvetica-Bold", 14)
    pdf.drawString(
        50,
        y,
        "Priority Skill Gaps"
    )

    y -= 25

    pdf.setFont("Helvetica", 10)

    if gap_items:
        for skill, gap, action in gap_items[:5]:

            pdf.drawString(
                60,
                y,
                f"- {skill}: Gap Level {gap}"
            )

            y -= 16

            if y < 80:
                pdf.showPage()
                y = height - 60
                pdf.setFont("Helvetica", 10)

    else:
        pdf.drawString(
            60,
            y,
            "No major gaps detected."
        )

        y -= 18

    # Action Plan
    y -= 15

    if y < 100:
        pdf.showPage()
        y = height - 60

    pdf.setFont("Helvetica-Bold", 14)
    pdf.drawString(
        50,
        y,
        "Personalized Action Plan"
    )

    y -= 25

    pdf.setFont("Helvetica", 10)

    for i, action in enumerate(actions, start=1):

        pdf.drawString(
            60,
            y,
            f"{i}. {action}"
        )

        y -= 18

        if y < 70:
            pdf.showPage()
            y = height - 60
            pdf.setFont("Helvetica", 10)

    # Footer
    pdf.setFont("Helvetica-Oblique", 8)

    pdf.drawString(
        50,
        35,
        "Generated by Adaptive Placement Coach - Academic Prototype"
    )

    pdf.save()

    buffer.seek(0)

    return buffer


